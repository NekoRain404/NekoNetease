//! Background task that drains the filesystem watcher's event channel,
//! deduplicates events within a 500 ms batching window, and applies the
//! resulting mutations to the database.
//!
//! Spawned once at startup from `main.rs`; exits on shutdown cancellation
//! after letting any in-flight batch's transaction commit so we don't
//! leave orphan rows behind.
//!
//! - [`dedup`] collapses a batch of raw watcher events to one event per path.
//! - [`suppress_self_writes`] drops the echo of our own tag writes.
//! - [`plan_batch`] decides which of the three things a batch turns out to be.
//! - [`reconcile`] extracts metadata and applies the batch to the database.
//! - [`RetryQueue`] holds what the store refused, for the next batch to replay.

mod dedup;
mod reconcile;

use std::path::PathBuf;

use tokio::sync::mpsc;
use tokio::time::{Duration, Instant};

use crate::state::AppState;
use crate::tasks::TaskSpawner;
use nekonetease_core::error::describe;
use nekonetease_core::utils::self_writes::SelfWrites;
use nekonetease_store::database::queries::scan::WatchedChange;
use nekonetease_store::media::ingest::watcher::FileEvent;

use dedup::deduplicate_events;
use reconcile::process_batch;

/// Total times one change is applied before the watcher gives up on it, its first attempt
/// included. Attempts are spaced by real batches, so a change still failing after this many is
/// not a transient lock; its row is left for the next full scan, which re-derives it from disk.
const MAX_ATTEMPTS: u32 = 3;

/// Distinct failed changes held between batches. A database that keeps rejecting writes can fail
/// a whole folder drop, and only a full scan repairs those rows; the ceiling stops a broken
/// database from pinning every failed file's metadata for the life of the process. 256 is more
/// than one batch of transient failures and stays invisible in RSS.
const MAX_RETRY_QUEUE: usize = 256;

/// A change the store could not apply, with how many times it has now failed.
struct Retry {
    change: WatchedChange,
    attempts: u32,
}

/// Changes waiting for the next batch. One entry per path, so a fresh event for a file replaces a
/// stale replay rather than being applied beside it.
#[derive(Default)]
struct RetryQueue {
    entries: Vec<Retry>,
}

impl RetryQueue {
    /// Takes everything queued, leaving the queue empty: the batch about to run either applies
    /// each change or hands it back with its attempt count advanced.
    fn take(&mut self) -> Vec<Retry> {
        std::mem::take(&mut self.entries)
    }

    /// Files what a batch could not apply. The oldest entries are abandoned past
    /// [`MAX_RETRY_QUEUE`], since the retry queue is a best-effort repair on the way to the next
    /// full scan rather than the only copy of anything.
    fn absorb(&mut self, failures: Vec<Retry>) {
        for failure in failures {
            let key = change_key(&failure.change);
            match self.entries.iter_mut().find(|queued| change_key(&queued.change) == key) {
                Some(queued) => *queued = failure,
                None => self.entries.push(failure),
            }
        }

        let excess = self.entries.len().saturating_sub(MAX_RETRY_QUEUE);
        if excess > 0 {
            self.entries.drain(..excess);
            log::warn!(
                "Watcher retry queue capped at {MAX_RETRY_QUEUE}; abandoned {excess} older failed \
                 event(s) to the next full scan"
            );
        }
    }
}

/// What identifies a change across batches: the path a later event for the same file would name.
/// A rename is filed under its target, which is where the file now lives.
fn change_key(change: &WatchedChange) -> PathBuf {
    match change {
        WatchedChange::Created { path, .. }
        | WatchedChange::Modified { path, .. }
        | WatchedChange::Removed(path) => path.clone(),
        WatchedChange::Renamed { to, .. } => to.clone(),
    }
}

/// Drop the events generated by our own tag writes.
///
/// **Two kinds, because a tag write lands as a rename.** `atomic_file::rewrite_with_sync` renames
/// an edited copy over the track, and the temp it comes from carries no audio extension, so
/// `classify_event` calls that a `Created`; backends reporting the rename as a plain modification
/// land on the other arm. A real `Renamed` is never ours, both its sides being audio. Suppressing
/// the `Created` is not cosmetic: `reconcile` extracts metadata for created paths too, so the echo
/// costs a re-hash, a lofty parse and an artwork extract before `apply_watch_batch` drops all three.
///
/// `take_recent` consumes the entry, so a path is suppressed at most once per
/// write. See [`SelfWrites`] for the accepted trades.
///
/// In place rather than `into_iter().filter().collect()`: nothing is suppressed in
/// the overwhelmingly common case (a batch of genuine external events), and that
/// case should not rebuild the `Vec`. `retain` visits each element exactly once, in
/// order, which is what `take_recent`'s consume-on-hit semantics need.
fn suppress_self_writes(batch: &mut Vec<FileEvent>, self_writes: &SelfWrites) {
    batch.retain(|event| match event {
        FileEvent::Created(path) | FileEvent::Modified(path) => !self_writes.take_recent(path),
        _ => true,
    });
}

/// What a drained batch amounts to, once the rescan flag and our own writes are accounted for.
enum BatchPlan {
    /// Nothing left worth a database round trip.
    Nothing,
    /// The watcher overflowed, so its per-file stream is truncated and untrustworthy.
    Rescan,
    /// Apply these, the echo of our own tag writes already dropped.
    Process(Vec<FileEvent>),
}

/// Decide what to do with a batch, dropping our own tag-write echoes on the way.
///
/// Correct for any batch rather than only a deduplicated one, which is the point of the `any`:
/// `process_batch` `unreachable!()`s on a `RescanNeeded`, and [`deduplicate_events`] collapsing
/// such a batch to the singleton is a second guarantee rather than the one being relied on.
///
/// The rescan is answered *before* the suppression because `take_recent` consumes: spending a
/// mark on a batch about to be discarded for a full reconcile would leave the real echo
/// unsuppressed inside its TTL. [`SelfWrites`]' own header states that ordering as settled and
/// cannot see this function, which is what these two lines are holding together.
fn plan_batch(mut batch: Vec<FileEvent>, self_writes: &SelfWrites) -> BatchPlan {
    if batch.is_empty() {
        return BatchPlan::Nothing;
    }
    if batch.iter().any(|e| matches!(e, FileEvent::RescanNeeded)) {
        return BatchPlan::Rescan;
    }

    let before = batch.len();
    suppress_self_writes(&mut batch, self_writes);
    let suppressed = before - batch.len();
    if suppressed > 0 {
        log::debug!("Suppressed {suppressed} watcher event(s) from our own tag writes");
    }

    if batch.is_empty() { BatchPlan::Nothing } else { BatchPlan::Process(batch) }
}

/// Spawn the file-event-processor on the shared task lifecycle so the main
/// shutdown sequence waits for the current batch's transaction to commit
/// before the runtime is torn down.
pub fn spawn(spawner: &TaskSpawner, state: &AppState, mut rx: mpsc::Receiver<FileEvent>) {
    let state = state.clone();

    spawner.spawn_cancellable(move |shutdown| async move {
        let mut retries = RetryQueue::default();

        loop {
            let first = tokio::select! {
                biased;
                () = shutdown.cancelled() => break,
                event = rx.recv() => match event {
                    Some(e) => e,
                    None => break,
                },
            };

            let mut batch = vec![first];
            let deadline = Instant::now() + Duration::from_millis(500);
            while let Ok(Some(event)) = tokio::time::timeout_at(deadline, rx.recv()).await {
                batch.push(event);
            }

            match plan_batch(deduplicate_events(batch), &state.self_writes) {
                BatchPlan::Nothing => {}
                BatchPlan::Rescan => {
                    log::warn!("Rescan requested via watcher overflow flag");
                    // The reconcile re-derives every enabled folder, so a held event is moot.
                    retries = RetryQueue::default();
                    crate::library::scan::reconcile_watched_folders(&state);
                    state.rescan_notice.bump();
                }
                BatchPlan::Process(batch) => {
                    log::info!("Processing batch of {} file events", batch.len());

                    let pending = retries.take();
                    let pending_count = pending.len();
                    // Don't bail on cancellation here — let the in-flight batch's tx
                    // commit so we don't leave orphan rows behind.
                    match process_batch(&state.db, &state.paths, &state.cover_cache, batch, pending)
                        .await
                    {
                        Ok(failed) => {
                            retries.absorb(failed);
                            state.library_changed.bump();
                        }
                        Err(e) => {
                            log::error!("File event batch processing failed: {}", describe(&e));
                            if pending_count > 0 {
                                log::warn!(
                                    "{pending_count} queued retried event(s) went with the aborted \
                                     batch; their rows wait for the next full scan"
                                );
                            }
                        }
                    }
                }
            }
        }
        log::info!("File event processor stopped");
    });

    log::info!("File event processor started");
}

